      SUBROUTINE WETBULB(RH,TDRY,BP,DEWP,TWET)
!
!NG   RH IN PERCENT, TDRY IN DEG C, BP IN MB
!NG   COMPUTE DEW POINT AND WET BULB TEMPERATURE
!NG   USING THE BISECTION METHOD
!NG 
!NG   N.GEORGAS, 10/26/2011, AFTER TVA APPENDIX D
!NG 
      NITER=50

      A1=7.5 ! 9.5 for ice
      B1=237.3 ! 265.5 for ice
      C1=0.7858 ! same for ice

      TDRY1=AMAX1(TDRY,0.01) ! DO NOT ALLOW ICE/SNOW FOR NOW
      TDRY1=AMIN1(TDRY,40.0) ! NOR REALLY HIGH TEMPERATURES
      RH=AMAX1(RH,0.1)
      RH=AMIN1(RH,100.)

!NG   COMPUTE PARTIAL WATER VAPOR PRESSURE OF DRY AIR
      EA = RH/100.*EXP(2.303*(A1*TDRY1/(TDRY1+B1)+C1))
!NG   COMPUTE DEW POINT TEMPERATURE (ANCILLARY)
      DEWP=237.3*(ALOG10(EA)-0.7858)/(7.5+0.7858-ALOG10(EA))
!NG   COMPUTE LATENT HEAT OF VAPORIZATION AT DRY BULB TEMP
      HLTDRY=2500.-2.39*TDRY1
!NG   COMPUTE MIXING RATIO OF AIR
      RDRY=0.622*EA/(BP-EA)

!NG   ASSUME INITIAL WET BULB DEPRESSION BOUNDS
      WETDEP1=25.
      WETDEP2=0.

!NG   WET BULB TEMPERATURE BOUNDS
      TWET0=TDRY1-WETDEP1
      TWET2=TDRY1-WETDEP2

      DO ITER=1,NITER
       TWET1=0.5*(TWET0+TWET2)
       IF(ABS(WETBCHK(TWET1,BP,HLTDRY,RDRY)).LT.1.E-7) GOTO 10
       IF(WETBCHK(TWET1,BP,HLTDRY,RDRY).GT.0) THEN
        TWET0=TWET1
       ELSE
        TWET2=TWET1
       ENDIF
      ENDDO
 10   TWET=TWET1
      TWET=AMIN1(50.,AMAX1(0.,TWET)) ! Make sure it is reasonable and not ice
!NG      WRITE (*,*)'FOUND',TWET0,TWET,TWET2,WETBCHK(TWET,BP,HLTDRY,RDRY)
!NG      WRITE (*,*)'IN',ITER,'ITERATIONS'
      RETURN
      END

      REAL FUNCTION WETBCHK(TWET,BP,HLTDRY,RDRY)
      A1=7.5 ! 9.5 for ice
      B1=237.3 ! 265.5 for ice
      C1=0.7858 ! same for ice
      CVAPOR1=0.45 ! kcal/(kg*C)
      CWATER1=0.999 ! kcal/(kg*C)
      CDRYAR1=0.24 ! kcal/(kg*C)
!NG   COMPUTE PARTIAL WATER VAPOR PRESSURE OF AIR AT WET BULB
      EAW=EXP(2.3026*(A1*TWET/(TWET+B1)+C1))
!NG   COMPUTE MIXING RATIO OF AIR AT WET BULB
      RWET=0.622*EAW/(BP-EAW)
!NG   COMPUTE LATENT HEAT OF VAPORIZATION AT WET BULB TEMP
      HLTWET=2500.-2.39*TWET
!NG   COMPUTE LEFT AND RIGHT HAND SIDES OF THE THERMODYNAMIC WET BULB EQUATION
      ELEFT=ALOG10(HLTWET/HLTDRY)
      ERIGHT=(CVAPOR1-CWATER1)/CVAPOR1*
     .  ALOG10( (CDRYAR1+CVAPOR1*RDRY)/(CDRYAR1+CVAPOR1*RWET) )
      WETBCHK=ELEFT-ERIGHT ! RESIDUAL
      RETURN
      END

