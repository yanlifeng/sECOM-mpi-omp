      SUBROUTINE NETCDF_READ_BC_MET(M,M_MAX,STR,WDS,WDD)
! Read meteorological boundary conditions netcdf file
! A. Jordi (Feb 5, 2015)

      INCLUDE 'comdeck'
      INCLUDE 'netcdf.inc'
      
      CHARACTER STR*80,STR_JUNK*31
      INTEGER START(2),COUNT(2)
      REAL WDS,WDD
      
      ! Open file
      ID_NC=NCOPN('run_data_bc_met.nc',NCNOWRIT,IERR)
      CALL NCAGTC(ID_NC,NCGLOBAL,'description',STR,80,IERR)

      ! Read variables
      ID_VAR=NCVID(ID_NC,'ALAT',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,ALAT,IERR)
      ID_VAR=NCVID(ID_NC,'ALON',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,ALON,IERR)
      ID_VAR=NCVID(ID_NC,'TR',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,TR,IERR)
      ID_VAR=NCVID(ID_NC,'WNDSH',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,WNDSH,IERR)
      ID_VAR=NCVID(ID_NC,'REFL',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,REFL,IERR)
      ID_VAR=NCVID(ID_NC,'CALCCLD',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,CALCCLD,IERR)
      ID_VAR=NCVID(ID_NC,'CALCSWOBS',IERR)
      CALL NCVGT(ID_NC,ID_VAR,START,COUNT,CALCSWOBS,IERR)
      START(1) = 1
      COUNT(1) = 20
      ID_VAR=NCVID(ID_NC,'OPTMBC',IERR)
      CALL NCVGTC(ID_NC,ID_VAR,START,COUNT,OPTMBC,20,IERR)
      START(1) = 1
      COUNT(1) = 4
      ID_VAR=NCVID(ID_NC,'OPTEXTC',IERR)
      CALL NCVGTC(ID_NC,ID_VAR,START,COUNT,OPTEXTC,4,IERR)

      M_MAX = 0
      IF(OPTMBC(1:8).EQ.'AVERAGED') THEN
        ID_DIM=NCDID(ID_NC,'NT',IERR)
        CALL NCDINQ(ID_NC,ID_DIM,STR_JUNK,M_MAX,IERR)  
        START(1) = M
        COUNT(1) = 1
        ID_VAR=NCVID(ID_NC,'TIME',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,TIME,IERR)
        T2M=TIME
        ID_VAR=NCVID(ID_NC,'WDS',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,WDS,IERR)
        ID_VAR=NCVID(ID_NC,'WDD',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,WDD,IERR)
        ID_VAR=NCVID(ID_NC,'HFLUX',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,HFLUX,IERR)
        ID_VAR=NCVID(ID_NC,'QPREC',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,QPREC,IERR)
        ID_VAR=NCVID(ID_NC,'QEVAP',IERR)
        CALL NCVGT(ID_NC,ID_VAR,START,COUNT,QEVAP,IERR)

       ELSE IF (OPTMBC(1:8).EQ.'LANDPFLX'.OR.
     .          OPTMBC(1:8).EQ.'AANDBFLX'.OR.
     .          OPTMBC(1:8).EQ.'RANDMFLX'.OR.
     .          OPTMBC(1:8).EQ.'SYNOPANB'.OR.
     .          OPTMBC(1:8).EQ.'SYNOPLNP'.OR.
     .          OPTMBC(1:8).EQ.'SYNOPRNM') THEN
         ID_DIM=NCDID(ID_NC,'NT',IERR)
         CALL NCDINQ(ID_NC,ID_DIM,STR_JUNK,M_MAX,IERR)  
         START(1) = M
         COUNT(1) = 1
         ID_VAR=NCVID(ID_NC,'TIME',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,TIME,IERR)
        T2M=TIME
         ID_VAR=NCVID(ID_NC,'WDS',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,WDS,IERR)
         ID_VAR=NCVID(ID_NC,'WDD',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,WDD,IERR)
         ID_VAR=NCVID(ID_NC,'SWOBS',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,SWOBS,IERR)
         ID_VAR=NCVID(ID_NC,'AIRTMP',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,AIRTMP,IERR)
         ID_VAR=NCVID(ID_NC,'RELHUM',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,RELHUM,IERR)
         ID_VAR=NCVID(ID_NC,'BAROP',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,BAROP,IERR)
         ID_VAR=NCVID(ID_NC,'CLD',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,CLD,IERR)
         ID_VAR=NCVID(ID_NC,'EXTC',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,EXTC,IERR)
         ID_VAR=NCVID(ID_NC,'QPREC',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,QPREC,IERR)
         ID_VAR=NCVID(ID_NC,'QEVAP',IERR)
         CALL NCVGT(ID_NC,ID_VAR,START,COUNT,QEVAP,IERR)
       END IF

      ! Close file
      CALL NCCLOS(ID_NC,IERR)
      
      RETURN
      END
