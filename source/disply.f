      SUBROUTINE DISPLY(ARRAY,AMASK,IM,JM,KK,SCALE,IUNIT)
      SAVE
!     VERSION(09/27/90)
!
!-----------------------------------------------------------------------
!      ARRAY=2D ARRAY(IM,JM) TO BE PRINTTED ON PAPER
!      IM   =IM DIMENSION OF ARRAY
!      JM   =JM DIMENSION OF ARRAY, IF ARRAY IS VERTICAL SLAB, JM=0
!      KK   =2ND DIMENSION OF ARRAY IF VERTICAL SLAB, OTHERWISE KK=0
!      SCALE=SCALES ALL VALUES BY CONSTANT AMOUNT
!-----------------------------------------------------------------------
!
      DIMENSION ARRAY(IM,KK),NUM(20),PLINE(20)
      DIMENSION AMASK(IM,KK)
      IF(SCALE.NE.0) GO TO 500
      DO 251 IS=1,IM,12
      IE=IS+11
      IF(IE.GT.IM) IE=IM
      IDIF=IE-IS+1
      DO 100 I=1,IDIF
 100  NUM(I)=IS+I-1
      WRITE(IUNIT,9990) (NUM(I),I=1,IDIF)
 9990 FORMAT(12I10,/)
      JMORKM=JM+KK
      DO 252 JORK=1,JMORKM
      IF(JM.NE.0) L=JMORKM+1-JORK
      IF(KK.NE.0) L=JORK
      WRITE(IUNIT,9966) L, (ARRAY(I,L),I=IS,IE)
 252  CONTINUE
      WRITE(IUNIT,9984)
 251  CONTINUE
 9966 FORMAT(1X,I2,12(1PE10.2))
 9984 FORMAT(//)
      RETURN
 500  CONTINUE
!
      IDIM=JM
      IF(JM.EQ.0) IDIM=KK
      CALL MAXMIN(ARRAY,AMASK,IM,IDIM,VMAX,VMIN)
      WRITE(IUNIT,110) SCALE,VMAX,VMIN
  110 FORMAT(//2X,'ACTUAL VALUE = PRINTED VALUE/',1PE9.2,
     .      5X,'MAX VALUE = ',1PE9.2,2X,'MIN VALUE = ',1PE9.2/)
      DO 751 IS=1,IM,20
      IE=IS+19
      IF(IE.GT.IM) IE=IM
      IDIF=IE-IS+1
      DO 600 I=1,IDIF
 600  NUM(I)=IS+I-1
      WRITE(IUNIT,9991) (NUM(I),I=1,IDIF)
 9991 FORMAT(3X,20I6,/)
      JMORKM=JM+KK
      DO 752 JORK=1,JMORKM
      IF(JM.NE.0) L=JMORKM+1-JORK
      IF(KK.NE.0) L=JORK
      DO 753 I=1,IDIF
      PLINE(I)=ARRAY(IS+I-1,L)*SCALE
 753  CONTINUE
      WRITE(IUNIT,9967) L,(PLINE(I),I=1,IDIF)
 752  CONTINUE
      WRITE(IUNIT,9984)
 751  CONTINUE
 9967 FORMAT(1X,I2,1X,20F6.2)
      RETURN
      END
