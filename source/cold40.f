! Conservative certified +0 cold-field path; no global persistent state.
      RECURSIVE LOGICAL FUNCTION C40_ZERO_ROW(N,A,B,C,D,E)
      IMPLICIT NONE
      INTEGER N,I,W
      REAL,INTENT(IN):: A(N),B(N),C(N),D(N),E(N)
      W=0
      DO I=1,N
        W=IOR(W,IOR(TRANSFER(A(I),0),TRANSFER(B(I),0)))
        W=IOR(W,IOR(TRANSFER(C(I),0),TRANSFER(D(I),0)))
        W=IOR(W,TRANSFER(E(I),0))
      ENDDO
      C40_ZERO_ROW=W.EQ.0
      END

      RECURSIVE LOGICAL FUNCTION C40_FP_OK()
      USE, INTRINSIC :: IEEE_ARITHMETIC
      IMPLICIT NONE
      TYPE(IEEE_ROUND_TYPE) R
      LOGICAL U,I,G
      C40_FP_OK=.FALSE.
      IF(STORAGE_SIZE(0.).NE.32.OR.STORAGE_SIZE(0).NE.32) RETURN
      IF(.NOT.IEEE_SUPPORT_DATATYPE(0.).OR..NOT.IEEE_SUPPORT_ROUNDING(IEEE_NEAREST,0.)) RETURN
      IF(.NOT.IEEE_SUPPORT_HALTING(IEEE_UNDERFLOW).OR..NOT.IEEE_SUPPORT_HALTING(IEEE_INEXACT)) RETURN
      CALL IEEE_GET_ROUNDING_MODE(R)
      CALL IEEE_GET_HALTING_MODE(IEEE_UNDERFLOW,U)
      CALL IEEE_GET_HALTING_MODE(IEEE_INEXACT,I)
      IF(.NOT.IEEE_SUPPORT_UNDERFLOW_CONTROL(0.)) RETURN
      CALL IEEE_GET_UNDERFLOW_MODE(G)
      C40_FP_OK=(R.EQ.IEEE_NEAREST).AND.G.AND..NOT.U.AND..NOT.I
      END

      RECURSIVE LOGICAL FUNCTION C40_WORD(X)
      IMPLICIT NONE
      REAL,INTENT(IN):: X
      INTEGER B
      B=IBCLR(TRANSFER(X,0),31)
      C40_WORD=B.EQ.0.OR.(B.GE.INT(Z'00800000').AND.B.LE.INT(Z'43000000'))
      END

      RECURSIVE LOGICAL FUNCTION C40_DEPTH(N,LO,HI,H,E,HH,EE,A,OFF)
      USE, INTRINSIC :: IEEE_EXCEPTIONS
      IMPLICIT NONE
      INTEGER N,LO,HI,OFF,I,B
      REAL,INTENT(IN):: H(N),E(N),HH(N),EE(N),A(N)
      REAL DEN
      TYPE(IEEE_STATUS_TYPE) OLD
      CALL IEEE_GET_STATUS(OLD)
      C40_DEPTH=.TRUE.
      DO I=LO,HI
        DEN=(H(I)+E(I)+HH(I+OFF)+EE(I+OFF))*A(I)
        B=IBCLR(TRANSFER(DEN,0),31)
! Require nonzero normal |den| >=2^-70; numerator bounded <2^50.
        IF(B.LT.INT(Z'1C800000')) THEN
          C40_DEPTH=.FALSE.
          EXIT
        ENDIF
      ENDDO
      CALL IEEE_SET_STATUS(OLD)
      END

