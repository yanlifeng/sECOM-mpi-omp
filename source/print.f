      SUBROUTINE PRINT(VAR,VMASK,IM,JM,IVAR,S,IUNIT,DEV)
!     VERSION(05/24/91)
!
      SAVE
      CHARACTER*3 DEV
      DIMENSION VAR(IM,JM),IVAR(IM,JM),VMASK(IM,JM)
      DO 100 J=1,JM
      DO 100 I=1,IM
!NG  100 IVAR(I,J)=NINT(S*VAR(I,J))
  100 IVAR(I,J)=NINT(S*VAR(I,J)*VMASK(I,J)) ! CNG01052010, 0 OUT PERMANENTLY DRY
      CALL MAXMIN(VAR,VMASK,IM,JM,VMAX,VMIN)
      IF(DEV.EQ.'LPR') THEN
       KN=20
      ELSE
       KN=10
      ENDIF
      IB=1
      IE=KN
      NUM=(IM-1)/KN
      IF(IM.LE.KN) NUM=1
      IF(IM.LE.KN) IE=IM
      DO 200 K=1,NUM
      IF(K.EQ.1) WRITE(IUNIT,110) S,VMAX,VMIN
  110 FORMAT(//2X,'ACTUAL VALUE = PRINTED VALUE/',1PE9.2,
     .      5X,'MAX VALUE = ',1PE9.2,2X,'MIN VALUE = ',1PE9.2)
      IF(DEV.EQ.'LPR') THEN
       WRITE(IUNIT,120) (I,I=IB,IE)
      ELSE
       WRITE(IUNIT,121) (I,I=IB,IE)
      ENDIF
  120 FORMAT(//10X,20I5)
  121 FORMAT(//10X,10I5)
      WRITE(IUNIT,130)
  130 FORMAT(/)
      DO 150 J=1,JM
      JJ=JM+1-J
      IF(DEV.EQ.'LPR') THEN
       WRITE(IUNIT,140) JJ,(IVAR(I,JJ),I=IB,IE),JJ
      ELSE
       WRITE(IUNIT,141) JJ,(IVAR(I,JJ),I=IB,IE),JJ
      ENDIF
  140 FORMAT(' ',I8,1X,20I5,1X,I8,' ')  
  141 FORMAT(' ',I8,1X,10I5,1X,I8,' ')   
  150 CONTINUE
      IB=IB+KN
      IE=IE+KN
  200 CONTINUE
      IF(IM.LE.KN) GO TO 300
      IE=IM
      IF(DEV.EQ.'LPR') THEN
       WRITE(IUNIT,120) (I,I=IB,IE)
      ELSE
       WRITE(IUNIT,121) (I,I=IB,IE)
      ENDIF
      WRITE(IUNIT,130)
      DO 250 J=1,JM
      JJ=JM+1-J
      IF(DEV.EQ.'LPR') THEN
       WRITE(IUNIT,140) JJ,(IVAR(I,JJ),I=IB,IE),JJ
      ELSE
       WRITE(IUNIT,141) JJ,(IVAR(I,JJ),I=IB,IE),JJ
      ENDIF
  250 CONTINUE
  300 RETURN
      END
