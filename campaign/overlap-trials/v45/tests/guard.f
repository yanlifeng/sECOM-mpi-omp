      PROGRAM GUARD45QA
      USE ISO_FORTRAN_ENV, ONLY: INT32
      REAL A(2,3)
      INTEGER(INT32) W(15)
      LOGICAL SECOM45_COR_OK,EXPECT,R
      CHARACTER*8 ARG
      DATA W /Z'00000000',Z'80000000',Z'01800000',Z'81800000',
     & Z'7F7FFFFF',Z'FF7FFFFF',Z'00000001',Z'007FFFFF',
     & Z'00800000',Z'017FFFFF',Z'7F800000',Z'FF800000',
     & Z'7FC00001',Z'7F800001',Z'FF800001'/
      CALL GET_COMMAND_ARGUMENT(1,ARG)
      DO I=1,SIZE(W)
        A=1.
        IF(STORAGE_SIZE(A(1,1)).EQ.32)
     &       A(2,3)=TRANSFER(W(I),A(1,1))
        EXPECT=I.LE.6.AND.ARG.EQ.'yes'
        R=SECOM45_COR_OK(A,2,3)
        IF(R.NEQV.EXPECT) THEN
          WRITE(*,*) I,R,EXPECT
          STOP 87
        ENDIF
      ENDDO
      END
