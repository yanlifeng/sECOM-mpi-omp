! QA only: exact mask/clamp window stitched into WINDOW30 by the script.
      PROGRAM WINDOWQA
      USE OMP_LIB
      USE IEEE_EXCEPTIONS, ONLY: IEEE_INVALID,IEEE_SUPPORT_HALTING,
     & IEEE_SET_HALTING_MODE,IEEE_SET_FLAG
      INCLUDE 'comdeck'
      REAL A30(IM,JM),B30(IM,JM)
      INTEGER DONE30,SEEN30,OVER30,PRE30,N30,FAST30
      COMMON /QA30/ DONE30,SEEN30,OVER30,PRE30,N30,FAST30
      INTEGER NT30,K30,OVERALL30,KMATCH30
      LOGICAL ROT30
      CHARACTER*12 ARG30
      CALL GET_COMMAND_ARGUMENT(1,BCTYPE)
      CALL GET_COMMAND_ARGUMENT(2,ARG30)
      ROT30=ARG30.EQ.'rotate'
      CALL GET_COMMAND_ARGUMENT(3,ARG30)
      READ(ARG30,*) NT30
      CALL GET_COMMAND_ARGUMENT(4,ARG30)
      READ(ARG30,*) FAST30
      CALL GET_COMMAND_ARGUMENT(5,ARG30)
      OVERALL30=0
      KMATCH30=0
      IF(BCTYPE.EQ.'PCLAMP'.OR.BCTYPE.EQ.'OCLAMP'.OR.
     & BCTYPE.EQ.'IRANDB'.OR.BCTYPE.EQ.'MIXED') KMATCH30=1
      NUMEBC=1
      IETA(1)=5
      JETA(1)=JMM1
      ICON(1)=4
      JCON(1)=JMM1
      ADVECT='NON-LINEAR'
      OPTEBC='DATA          LINEAR'
      H1=2.3
      H2=3.9
      H=4.
      IF(ARG30.EQ.'invalid'.OR.ARG30.EQ.'trap') H=-64.
      D=4.
      GRAV=9.81
      DTE=0.1
      TLAG=0.8
      TIME=0.1
      AAM2D=0.2
      FSM=1.
      FSM(5,JMM1)=0.5
      FSM(6,JMM1)=0.
      FSM(1,2)=-0.
      DUM=1.
      DVM=1.
      DUMWAD=1.
      DVMWAD=1.
      DO J=1,JM
        DO I=1,IM
          EL(I,J)=0.125 + I*0.001
          ELB(I,J)=0.1 + J*0.001
          UA(I,J)=0.001*(I+J)
          VA(I,J)=0.003*(I-J)
          UAB(I,J)=0.99*UA(I,J)
          VAB(I,J)=0.98*VA(I,J)
        ENDDO
      ENDDO
      OPEN(93,FILE='states.bin',ACCESS='STREAM',FORM='UNFORMATTED',STATUS='REPLACE')
!$OMP PARALLEL DEFAULT(SHARED) NUM_THREADS(NT30) PRIVATE(K30)
! Set flags per worker: SINGLE is allowed to elect a non-main thread,
! which need not inherit this runtime's main-thread trap mask.
      IF(ARG30.EQ.'invalid'.OR.ARG30.EQ.'trap') THEN
        IF(IEEE_SUPPORT_HALTING(IEEE_INVALID))
     &    CALL IEEE_SET_HALTING_MODE(IEEE_INVALID,ARG30.EQ.'trap')
        CALL IEEE_SET_FLAG(IEEE_INVALID,.FALSE.)
      ENDIF
      DO K30=1,10
!$OMP SINGLE
        N30=OMP_GET_NUM_THREADS()
        IF(N30.NE.NT30) STOP 61
        DONE30=0
        SEEN30=0
        OVER30=0
        PRE30=0
        DO J=1,JM
          DO I=1,IM
            ELF(I,J)=0.03125*(I+2*J+K30)
          ENDDO
        ENDDO
!$OMP END SINGLE
        CALL WINDOW30(A30,B30,ROT30)
!$OMP SINGLE
        IF(DONE30.NE.1.OR.SEEN30.NE.1.OR.PRE30.NE.KMATCH30) STOP 62
        OVERALL30=OVERALL30+OVER30
        WRITE(93) ELF,FLUXUA,FLUXVA,TPS,A30,B30
!$OMP END SINGLE
      ENDDO
!$OMP END PARALLEL
      CLOSE(93)
      IF(FAST30.EQ.1.AND.N30.GT.1) THEN
        IF(OVERALL30.NE.10) STOP 63
      ELSE
        IF(OVERALL30.NE.0) STOP 64
      ENDIF
      WRITE(*,*) 'QA30 steps,overlaps,workers:',10,OVERALL30,N30
      END

! Delay a row that contains the open boundary, not the ADVAVE witness row.
      SUBROUTINE STALL30
      USE OMP_LIB
      INTEGER DONE30,SEEN30,OVER30,PRE30,N30,FAST30,VAL30
      COMMON /QA30/ DONE30,SEEN30,OVER30,PRE30,N30,FAST30
      DOUBLE PRECISION START30
      IF(N30.EQ.1) RETURN
      START30=OMP_GET_WTIME()
      IF(FAST30.EQ.1) THEN
! Handshake: require another worker to actually enter an ADVAVE row.
        DO
!$OMP ATOMIC READ
          VAL30=SEEN30
          IF(VAL30.NE.0) RETURN
          IF(OMP_GET_WTIME()-START30.GT.5.D0) STOP 65
        ENDDO
      ELSE
! Reference / gated mode should not be able to enter the clamp early.
        DO WHILE(OMP_GET_WTIME()-START30.LT.0.025D0)
        ENDDO
      ENDIF
      END

      SUBROUTINE MASKED30
      INTEGER DONE30,SEEN30,OVER30,PRE30,N30,FAST30
      COMMON /QA30/ DONE30,SEEN30,OVER30,PRE30,N30,FAST30
!$OMP ATOMIC WRITE
      DONE30=1
      END

      SUBROUTINE ENTER_ADV30
      INTEGER DONE30,SEEN30,OVER30,PRE30,N30,FAST30,VAL30
      COMMON /QA30/ DONE30,SEEN30,OVER30,PRE30,N30,FAST30
! Test the state before releasing the delayed worker.
!$OMP ATOMIC READ
      VAL30=DONE30
      IF(VAL30.EQ.0) THEN
!$OMP ATOMIC WRITE
        OVER30=1
      ENDIF
!$OMP ATOMIC WRITE
      SEEN30=1
      END

      SUBROUTINE BEFORE_CLAMP30
      INTEGER DONE30,SEEN30,OVER30,PRE30,N30,FAST30,VAL30
      COMMON /QA30/ DONE30,SEEN30,OVER30,PRE30,N30,FAST30
!$OMP ATOMIC READ
      VAL30=DONE30
      IF(VAL30.NE.1) STOP 66
      PRE30=PRE30+1
      END

      SUBROUTINE CHECK_IEEE30(X30)
      USE IEEE_ARITHMETIC, ONLY: IEEE_IS_NAN
      USE IEEE_EXCEPTIONS, ONLY: IEEE_INVALID,IEEE_GET_FLAG
      REAL X30
      LOGICAL FLAG30
      IF(IEEE_IS_NAN(X30)) THEN
        CALL IEEE_GET_FLAG(IEEE_INVALID,FLAG30)
        IF(FLAG30) STOP 67
        STOP 68
      ENDIF
      END
